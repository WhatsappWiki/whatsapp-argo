"""Hand-derived spec/profile edges, independent of the official corpus.

All expected bytes below are literal Label/UTF-8 encodings. They were not
generated by this package or labelled as WhatsApp network observations.
"""
from copy import deepcopy

import pytest

from whatsapp_argo import ArgoError, FieldErrors, Header, read, write


USER = {"type": "RECORD", "fields": [
    {"name": "id", "of": {"type": "STRING"}, "omittable": False},
    {"name": "name", "of": {"type": "STRING"}, "omittable": False},
]}
SCHEMA = {"type": "RECORD", "fields": [
    {"name": "data", "of": {"type": "NULLABLE", "of": {"type": "RECORD", "fields": [
        {"name": "users", "of": {"type": "ARRAY", "of": {"type": "NULLABLE", "of": USER}}, "omittable": False},
    ]}}, "omittable": False},
]}
INLINE_TYPED = Header(inline_everything=True, out_of_band_field_errors=False, self_describing_errors=False)
ERROR = {"message": "bad", "locations": [{"line": 2, "column": 3}],
         "path": ["name"], "extensions": {"code": 7}}

# Header 01; data non-null 00; users length 02; ERROR 05; one error 02;
# message 06 + "bad"; one location 02 + line 04 + column 06;
# relative PATH length 02 + local field ordinal 02 (= name at index 1).
# EXTENSIONS is DESC object 04 + count 02 + key length 08 + "code";
# DESC Int marker 0c + zig-zag 7 = 0e.
# The official omittable profile prefixes that EXTENSIONS with non-null 00.
RELATIVE = {
    "nullable": "0100020502066261640204060202040208636f64650c0e",
    "omittable": "010002050206626164020406020200040208636f64650c0e",
}
# Compatibility layout encodes full PATH [users, 0, name] -> [0, 0, 1].
ROOT_COMPAT = {
    "nullable": "01000205020662616402040606000002040208636f64650c0e",
    "omittable": "0100020502066261640204060600000200040208636f64650c0e",
}


def nested(error):
    return {"data": {"users": [FieldErrors((error,))]}}


@pytest.mark.parametrize("encoding", ["nullable", "omittable"])
def test_nested_relative_inline_paths_from_spec(encoding):
    expected = nested(deepcopy(ERROR))
    raw = bytes.fromhex(RELATIVE[encoding])
    document = read(raw, SCHEMA, error_encoding=encoding)
    assert document.value == expected
    assert write(expected, SCHEMA, header=INLINE_TYPED, error_encoding=encoding) == raw
    assert write(document) == raw
    # Interpreting local field ordinal 1 against data's one-field root fails.
    with pytest.raises(ArgoError):
        read(raw, SCHEMA, error_encoding=encoding, inline_error_paths="root")


@pytest.mark.parametrize("encoding", ["nullable", "omittable"])
def test_explicit_upstream_root_path_compatibility(encoding):
    error = deepcopy(ERROR)
    error["path"] = ["users", 0, "name"]
    expected = nested(error)
    raw = bytes.fromhex(ROOT_COMPAT[encoding])
    document = read(raw, SCHEMA, error_encoding=encoding, inline_error_paths="root")
    assert document.value == expected
    assert write(expected, SCHEMA, header=INLINE_TYPED,
                 error_encoding=encoding, inline_error_paths="root") == raw
    assert write(document) == raw
    with pytest.raises(ArgoError):
        read(raw, SCHEMA, error_encoding=encoding)


@pytest.mark.parametrize("flag", [0x09, 0x03])
def test_self_describing_error_custom_fields_from_spec_note(flag):
    # DESC object with two fields: message String("bad"), code Int(7).
    raw = bytes([flag]) + bytes.fromhex("04040e6d657373616765080662616408636f64650c0e")
    schema = {"type": "ERROR"}
    expected = {"message": "bad", "code": 7}
    document = read(raw, schema)
    assert document.value == expected
    assert write(document) == raw
    document.value["code"] = 8
    changed = write(document)
    assert changed != raw
    assert read(changed, schema).value == {"message": "bad", "code": 8}


def test_spec_nullable_error_null_optionals():
    # Inline Header; one-byte message "x"; three Null Labels (-1 -> 01).
    raw = bytes.fromhex("010278010101")
    expected = {"message": "x", "locations": None, "path": None, "extensions": None}
    document = read(raw, {"type": "ERROR"}, error_encoding="nullable")
    assert document.value == expected
    assert write(expected, {"type": "ERROR"}, header=INLINE_TYPED, error_encoding="nullable") == raw
    assert write(document) == raw


def test_spec_nullable_empty_optionals_distinct_from_null():
    # Empty locations/path lengths are 00; empty DESC object is 04 00.
    raw = bytes.fromhex("01027800000400")
    expected = {"message": "x", "locations": [], "path": [], "extensions": {}}
    path_schema = {"type": "RECORD", "fields": []}
    document = read(raw, {"type": "ERROR"}, error_encoding="nullable", path_schema=path_schema)
    assert document.value == expected
    assert write(expected, {"type": "ERROR"}, header=INLINE_TYPED,
                 error_encoding="nullable", path_schema=path_schema) == raw


@pytest.mark.parametrize("key", ["locations", "path", "extensions"])
def test_nullable_profile_requires_explicit_optionals(key):
    value = {"message": "x", "locations": None, "path": None, "extensions": None}
    del value[key]
    with pytest.raises(ArgoError):
        write(value, {"type": "ERROR"}, header=INLINE_TYPED, error_encoding="nullable")


def test_typed_errors_still_reject_unknown_keys():
    with pytest.raises(ArgoError):
        write({"message": "x", "code": 7}, {"type": "ERROR"}, header=INLINE_TYPED)


def test_error_profile_does_not_silently_guess():
    # Null (-1) and Absent (-2) are deliberately separate profiles.
    with pytest.raises(ArgoError):
        read(bytes.fromhex("010278030303"), {"type": "ERROR"}, error_encoding="nullable")
    with pytest.raises(ArgoError):
        read(bytes.fromhex("010278010101"), {"type": "ERROR"}, error_encoding="omittable")
